-- Seeex complete PostgreSQL schema
-- Policy: no database foreign keys. Relationships are validated in the application layer.
-- PostgreSQL 15+

create schema if not exists seeex;
set search_path = seeex, public;

create extension if not exists pgcrypto;

-- Organization and accounts
create table if not exists company_profile (
  id bigint generated by default as identity primary key,
  company_code varchar(64) not null unique,
  company_name varchar(128) not null,
  timezone varchar(64) not null default 'Asia/Shanghai',
  logo_url varchar(512),
  wecom_enabled boolean not null default false,
  wecom_corp_id varchar(128),
  wecom_agent_id varchar(64),
  wecom_secret_ref varchar(256),
  wecom_token_ref varchar(256),
  wecom_aes_key_ref varchar(256),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz
);

create table if not exists employee (
  id bigint generated by default as identity primary key,
  employee_no varchar(32) not null unique,
  display_name varchar(128) not null,
  internal_title varchar(128),
  internal_mobile varchar(32),
  internal_email varchar(256),
  avatar_url varchar(512),
  status varchar(32) not null default 'ACTIVE' check (status in ('ACTIVE','DISABLED','LEFT','LOCKED')),
  source varchar(32) not null default 'LOCAL' check (source in ('LOCAL','WE_COM','IMPORT')),
  primary_department_id bigint,
  job_grade_id bigint,
  created_at timestamptz not null default now(),
  created_by bigint,
  updated_at timestamptz not null default now(),
  updated_by bigint,
  deleted_at timestamptz,
  deleted_by bigint
);
create index if not exists ix_employee_status on employee(status) where deleted_at is null;
create index if not exists ix_employee_department on employee(primary_department_id) where deleted_at is null;

create table if not exists employee_account (
  id bigint generated by default as identity primary key,
  employee_id bigint not null,
  login_phone varchar(32) not null,
  phone_verified boolean not null default false,
  password_hash varchar(255),
  login_enabled boolean not null default true,
  last_login_at timestamptz,
  failed_login_count integer not null default 0 check (failed_login_count >= 0),
  locked_until timestamptz,
  is_primary boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz
);
create unique index if not exists ux_employee_account_phone on employee_account(login_phone) where deleted_at is null and login_enabled = true;
create unique index if not exists ux_employee_primary_account on employee_account(employee_id) where deleted_at is null and is_primary = true;

create table if not exists employee_phone_history (
  id bigint generated by default as identity primary key,
  employee_account_id bigint not null,
  phone varchar(32) not null,
  valid_from timestamptz not null,
  valid_to timestamptz,
  change_reason varchar(128),
  created_at timestamptz not null default now(),
  check (valid_to is null or valid_to > valid_from)
);
create index if not exists ix_phone_history_account on employee_phone_history(employee_account_id, valid_from desc);

create table if not exists department (
  id bigint generated by default as identity primary key,
  external_id varchar(128),
  external_parent_id varchar(128),
  parent_id bigint,
  department_code varchar(64) not null unique,
  name varchar(128) not null,
  sort_order integer not null default 0,
  status varchar(32) not null default 'ACTIVE',
  source varchar(32) not null default 'LOCAL',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz
);
create unique index if not exists ux_department_external on department(external_id) where external_id is not null and deleted_at is null;
create index if not exists ix_department_parent on department(parent_id) where deleted_at is null;

create table if not exists employee_department (
  id bigint generated by default as identity primary key,
  employee_id bigint not null,
  department_id bigint not null,
  is_primary boolean not null default false,
  is_leader boolean not null default false,
  source varchar(32) not null default 'LOCAL',
  effective_at timestamptz not null default now(),
  expires_at timestamptz,
  revoked_at timestamptz,
  revoked_by bigint,
  created_at timestamptz not null default now(),
  check (expires_at is null or expires_at > effective_at)
);
create unique index if not exists ux_employee_department_active on employee_department(employee_id, department_id) where revoked_at is null;
create unique index if not exists ux_employee_primary_department on employee_department(employee_id) where is_primary = true and revoked_at is null;

create table if not exists job_grade (
  id bigint generated by default as identity primary key,
  name varchar(128) not null,
  level_value integer,
  sort_order integer not null default 0,
  external_provider varchar(32),
  external_id varchar(128),
  external_name varchar(128),
  status varchar(32) not null default 'ACTIVE',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz
);
create unique index if not exists ux_job_grade_external on job_grade(external_provider, external_id) where external_provider is not null and external_id is not null and deleted_at is null;

-- Authentication and external identity
create table if not exists auth_session (
  id bigint generated by default as identity primary key,
  employee_account_id bigint not null,
  access_token_hash varchar(128) not null unique,
  refresh_token_hash varchar(128) not null unique,
  issued_at timestamptz not null default now(),
  access_expires_at timestamptz not null,
  refresh_expires_at timestamptz not null,
  revoked_at timestamptz,
  ip_address inet,
  user_agent varchar(512),
  last_used_at timestamptz,
  check (refresh_expires_at > access_expires_at)
);
create index if not exists ix_auth_session_access_expiry on auth_session(access_expires_at);
create index if not exists ix_auth_session_refresh_expiry on auth_session(refresh_expires_at);
create index if not exists ix_auth_session_revoked on auth_session(revoked_at);

create table if not exists auth_oauth_state (
  id bigint generated by default as identity primary key,
  provider varchar(32) not null,
  state_hash varchar(128) not null unique,
  redirect_uri varchar(512) not null,
  return_path varchar(512),
  expires_at timestamptz not null,
  used_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists ix_oauth_state_lookup on auth_oauth_state(provider, expires_at, used_at);

create table if not exists auth_exchange_code (
  id bigint generated by default as identity primary key,
  employee_account_id bigint not null,
  code_hash varchar(128) not null unique,
  expires_at timestamptz not null,
  used_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists ix_exchange_code_lookup on auth_exchange_code(expires_at, used_at);

create table if not exists employee_external_identity (
  id bigint generated by default as identity primary key,
  employee_id bigint not null,
  provider varchar(32) not null,
  external_id varchar(256) not null,
  external_union_id varchar(256),
  external_name varchar(128),
  external_mobile varchar(32),
  external_email varchar(256),
  external_position varchar(128),
  external_avatar varchar(512),
  external_status varchar(32),
  status varchar(32) not null default 'ACTIVE',
  first_synced_at timestamptz,
  last_synced_at timestamptz,
  last_sync_run_id bigint,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists ux_external_identity on employee_external_identity(provider, external_id);
create index if not exists ix_external_identity_employee on employee_external_identity(employee_id, provider);

-- RBAC
create table if not exists role (
  id bigint generated by default as identity primary key,
  code varchar(128) not null unique,
  name varchar(128) not null,
  description text,
  status varchar(32) not null default 'ACTIVE',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz
);

create table if not exists resource (
  id bigint generated by default as identity primary key,
  parent_id bigint,
  resource_type varchar(32) not null check (resource_type in ('MENU','PAGE','TAB','BUTTON','API')),
  code varchar(128) not null unique,
  permission_code varchar(160) not null unique,
  name varchar(128) not null,
  path varchar(512),
  component varchar(256),
  icon varchar(128),
  sort_order integer not null default 0,
  status varchar(32) not null default 'ACTIVE',
  is_visible boolean not null default true,
  is_public boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz
);
create index if not exists ix_resource_parent on resource(parent_id, sort_order);

create table if not exists role_resource (
  id bigint generated by default as identity primary key,
  role_id bigint not null,
  resource_id bigint not null,
  effect varchar(16) not null check (effect in ('ALLOW','DENY')),
  effective_at timestamptz not null default now(),
  expires_at timestamptz,
  created_at timestamptz not null default now(),
  check (expires_at is null or expires_at > effective_at),
  unique (role_id, resource_id, effect)
);
create index if not exists ix_role_resource_active on role_resource(role_id, resource_id, effective_at, expires_at);

create table if not exists subject_role_assignment (
  id bigint generated by default as identity primary key,
  subject_type varchar(32) not null check (subject_type in ('EMPLOYEE','DEPARTMENT','JOB_GRADE')),
  subject_id bigint not null,
  role_id bigint not null,
  assignment_source varchar(32) not null check (assignment_source in ('MANUAL','JOB_GRADE','DEPARTMENT','WE_COM','SYSTEM')),
  source_key varchar(128),
  sync_run_id bigint,
  department_scope varchar(32) check (department_scope in ('CURRENT','DESCENDANTS','CURRENT_AND_DESCENDANTS')),
  effective_at timestamptz not null default now(),
  expires_at timestamptz,
  revoked_at timestamptz,
  revoked_by bigint,
  created_at timestamptz not null default now(),
  check (expires_at is null or expires_at > effective_at)
);
create index if not exists ix_subject_role_active on subject_role_assignment(subject_type, subject_id, revoked_at, expires_at);
create index if not exists ix_subject_role_role on subject_role_assignment(role_id, revoked_at);

create table if not exists data_scope (
  id bigint generated by default as identity primary key,
  role_id bigint not null,
  resource_id bigint,
  scope_type varchar(32) not null check (scope_type in ('SELF','DEPARTMENT','DEPARTMENT_AND_DESCENDANTS','ALL','CUSTOM')),
  scope_config jsonb,
  effective_at timestamptz not null default now(),
  expires_at timestamptz,
  created_at timestamptz not null default now(),
  check (expires_at is null or expires_at > effective_at),
  check ((scope_type = 'CUSTOM' and scope_config is not null) or (scope_type <> 'CUSTOM'))
);
create index if not exists ix_data_scope_role_resource on data_scope(role_id, resource_id, effective_at, expires_at);

-- WeCom synchronization
create table if not exists wecom_grade_mapping (
  id bigint generated by default as identity primary key,
  external_field varchar(128) not null,
  external_value varchar(256) not null,
  job_grade_id bigint not null,
  source varchar(32) not null default 'MANUAL',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (external_field, external_value)
);

create table if not exists external_identity_conflict (
  id bigint generated by default as identity primary key,
  provider varchar(32) not null,
  external_id varchar(256) not null,
  candidate_employee_ids jsonb not null,
  reason varchar(128) not null,
  status varchar(32) not null default 'OPEN' check (status in ('OPEN','RESOLVED','IGNORED')),
  resolved_employee_id bigint,
  resolved_by bigint,
  resolved_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists ix_identity_conflict_status on external_identity_conflict(status, created_at);

create table if not exists sync_run (
  id bigint generated by default as identity primary key,
  run_no varchar(32) not null unique,
  sync_type varchar(32) not null check (sync_type in ('FULL','INCREMENTAL','REPAIR')),
  status varchar(32) not null check (status in ('PENDING','RUNNING','SUCCESS','PARTIAL','FAILED')),
  started_at timestamptz,
  finished_at timestamptz,
  total_count integer not null default 0,
  success_count integer not null default 0,
  failed_count integer not null default 0,
  error_message text,
  created_at timestamptz not null default now()
);
create index if not exists ix_sync_run_status on sync_run(status, created_at desc);

create table if not exists sync_event (
  id bigint generated by default as identity primary key,
  event_no varchar(32) not null unique,
  provider varchar(32) not null,
  event_type varchar(128) not null,
  event_id varchar(256),
  payload_hash varchar(128) not null,
  payload_encrypted text,
  status varchar(32) not null check (status in ('RECEIVED','PROCESSING','SUCCESS','RETRY_WAIT','DEAD_LETTER')),
  retry_count integer not null default 0,
  next_retry_at timestamptz,
  received_at timestamptz not null default now(),
  processed_at timestamptz,
  error_message text,
  sync_run_id bigint
);
create unique index if not exists ux_sync_event_external on sync_event(provider, event_type, event_id) where event_id is not null;
create unique index if not exists ux_sync_event_payload on sync_event(provider, event_type, payload_hash) where event_id is null;
create index if not exists ix_sync_event_retry on sync_event(status, next_retry_at);

-- File metadata
create table if not exists file_metadata (
  id bigint generated by default as identity primary key,
  idempotency_key varchar(128) not null unique,
  tenant_id varchar(64) not null,
  owner_id varchar(64) not null,
  biz_type varchar(64),
  biz_id varchar(128),
  bucket_name varchar(128) not null,
  object_key varchar(512) not null unique,
  file_name varchar(255) not null,
  content_type varchar(128) not null,
  file_size bigint not null check (file_size > 0),
  etag varchar(128),
  sha256 char(64),
  visibility varchar(32) not null check (visibility in ('PRIVATE','PUBLIC','TEMP','QUARANTINE')),
  status varchar(32) not null check (status in ('PENDING','CONFIRMED','DELETED')),
  storage_class varchar(32) not null default 'STANDARD',
  created_at timestamptz not null default now(),
  confirmed_at timestamptz,
  deleted_at timestamptz,
  updated_at timestamptz not null default now()
);
create index if not exists ix_file_owner_status on file_metadata(tenant_id, owner_id, status);
create index if not exists ix_file_business on file_metadata(tenant_id, biz_type, biz_id);
create index if not exists ix_file_cleanup on file_metadata(status, created_at);

create table if not exists audit_log (
  id bigint generated by default as identity primary key,
  log_no varchar(32) not null unique,
  operator_employee_id bigint,
  action varchar(128) not null,
  resource_type varchar(32),
  resource_id bigint,
  before_data jsonb,
  after_data jsonb,
  request_id varchar(128),
  ip_address inet,
  user_agent varchar(512),
  created_at timestamptz not null default now()
);
create index if not exists ix_audit_operator_time on audit_log(operator_employee_id, created_at desc);
create index if not exists ix_audit_resource on audit_log(resource_type, resource_id, created_at desc);

