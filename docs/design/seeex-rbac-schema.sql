  updated_at timestamptz not null default current_timestamp, updated_by bigint,
  deleted_at timestamptz, deleted_by bigint,
  constraint ck_job_grade_status check (status in ('ACTIVE','DISABLED'))
);

create table employee (
  id bigint generated by default as identity primary key,
  employee_no varchar(32) not null, display_name varchar(128) not null,
  internal_title varchar(128), internal_mobile varchar(32), internal_email varchar(256), avatar_url varchar(512),
  status varchar(32) not null default 'ACTIVE', source varchar(32) not null default 'LOCAL',
  primary_department_id bigint references department(id), job_grade_id bigint references job_grade(id),
