  deleted_at timestamptz, deleted_by bigint,
  constraint ck_employee_status check (status in ('ACTIVE','DISABLED','LEFT','LOCKED')),
  constraint ck_employee_source check (source in ('LOCAL','WE_COM','IMPORT'))
