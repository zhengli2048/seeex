create table sync_run (
  id bigint generated by default as identity primary key, run_no varchar(32) not null,
  sync_type varchar(32) not null, status varchar(32) not null, started_at timestamptz, finished_at timestamptz,
  total_count integer not null default 0, success_count integer not null default 0, failed_count integer not null default 0,
