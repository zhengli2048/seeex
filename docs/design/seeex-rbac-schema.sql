create table company_profile (
  id bigint generated by default as identity primary key,
  company_code varchar(64) not null,
  company_name varchar(128) not null,
  timezone varchar(64) not null default 'Asia/Shanghai',
  logo_url varchar(512),
  wecom_enabled boolean not null default false,
  wecom_corp_id varchar(128),
  wecom_agent_id varchar(64),
  wecom_secret_ref varchar(256),
  wecom_token_ref varchar(256),
  wecom_aes_key_ref varchar(256),
  created_at timestamptz not null default current_timestamp,
  created_by bigint, updated_at timestamptz not null default current_timestamp,
  updated_by bigint, deleted_at timestamptz, deleted_by bigint,
  constraint ck_company_singleton check (id = 1)
);

create table department (
  id bigint generated by default as identity primary key,
  external_id varchar(128), external_parent_id varchar(128), parent_id bigint references department(id),
  department_code varchar(64), name varchar(128) not null, sort_order integer not null default 0,
  status varchar(32) not null default 'ACTIVE', source varchar(32) not null default 'LOCAL',
  created_at timestamptz not null default current_timestamp, created_by bigint,
  updated_at timestamptz not null default current_timestamp, updated_by bigint,
  deleted_at timestamptz, deleted_by bigint,
  constraint ck_department_status check (status in ('ACTIVE','DISABLED'))
);

create table job_grade (
  id bigint generated by default as identity primary key,
  name varchar(128) not null, level_value integer, sort_order integer not null default 0,
